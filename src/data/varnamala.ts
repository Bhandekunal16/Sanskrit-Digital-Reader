export type VarnamalaSection = 'vowels' | 'consonants' | 'conjuncts' | 'vedic';
export type SvaraType = 'hrasva' | 'dirgha' | 'sandhyaksara' | 'ayogavaha';
export type VargaType = 'ka-varga' | 'ca-varga' | 'ta-retro-varga' | 'ta-dental-varga' | 'pa-varga' | 'antastha' | 'ushman' | 'samyukta' | 'vaidika';

export interface ExemplarWord {
  devanagari: string;
  iast: string;
  meaningEn: string;
  meaningHi: string;
  meaningMr: string;
  category: string;
  audioText?: string;
}

export interface MatraEntry {
  vowelDevanagari: string;
  vowelIast: string;
  matraSign: string;
  sampleCombination: string; // e.g., 'का'
  sampleIast: string; // e.g., 'kā'
  nameDevanagari: string;
  nameEn: string;
}

export interface VarnaLetter {
  id: string;
  devanagari: string;
  iast: string;
  ipa: string;
  section: VarnamalaSection;
  subType?: SvaraType;
  varga?: VargaType;
  vargaName?: string;
  
  // Phonological Classification
  placeEn: string;
  placeSa: string;
  placeTerm: string;
  organEn: string;
  organSa: string;
  
  // Effort (Prayatna)
  internalEffortSa: string; // आभ्यन्तर प्रयत्न
  internalEffortEn: string;
  externalEffortSa: string; // बाह्य प्रयत्न
  externalEffortEn: string;
  voicing: 'voiced' | 'unvoiced';
  aspiration: 'unaspirated' | 'aspirated' | 'nasal' | 'vowel';
  
  // Duration & Matra
  matraDuration?: string; // १ मात्रा (ह्रस्व) / २ मात्रा (दीर्घ) / ३ मात्रा (प्लुत)
  matraSign?: string;
  
  // Academic & Traditional details
  paniniSutra?: string;
  paniniSutraMeaning?: string;
  description: string;
  pronunciationTip: string;
  
  // Exemplar Word
  exemplar: ExemplarWord;
  
  // Acoustic Formant & Synthesis Frequencies (for Web Audio API realistic synthesis)
  audioParams: {
    baseFreq: number; // Fundamental frequency (Hz)
    formantF1: number; // 1st formant (vocal tract height)
    formantF2: number; // 2nd formant (vocal tract front/back)
    formantF3: number; // 3rd formant
    duration: number; // seconds
    type: 'vowel' | 'stop' | 'nasal' | 'fricative' | 'semivowel' | 'aspirate';
    isAspirated?: boolean;
    isVoiced?: boolean;
  };
}

